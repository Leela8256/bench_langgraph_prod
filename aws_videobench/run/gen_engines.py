"""Generate docker-compose.engines.yml — K side-by-side engine instances.

Why K engines: threads=32 proved the ~6-core ceiling is per-ENGINE and not
configurable (5.59 vs 5.85 effective cores, identical output). The box has
32 vCPUs, so throughput scales horizontally: K engines x ~6 cores each.
Engines share the warm rr-model-cache volume READ-mostly; the wave runner
boots rr1 alone first on a cold cache so concurrent first-boot pip installs
never race.

No host ports: the driver containers reach engines by service name
(ws://rr<k>:5565) on the compose network.

  python3 gen_engines.py <K> > docker-compose.engines.yml
"""

import sys

K = int(sys.argv[1]) if len(sys.argv) > 1 else 5
print("# GENERATED by run/gen_engines.py — do not edit by hand")
print("services:")
for k in range(1, K + 1):
    print(f"""  rr{k}:
    image: videobench-rocketride:3.3.1
    platform: linux/amd64
    container_name: videobench-rr{k}
    environment:
      ROCKETRIDE_URI: ws://127.0.0.1:5565/task/service
      ROCKETRIDE_APIKEY: local-dev
      RR_HOST: "0.0.0.0"
    volumes:
      - rr-model-cache:/root/.cache
    healthcheck:
      test: ["CMD", "python", "-c",
             "import socket,sys; s=socket.socket(); s.settimeout(3); sys.exit(s.connect_ex(('127.0.0.1',5565)))"]
      interval: 10s
      timeout: 5s
      retries: 30
      start_period: 30s""")
